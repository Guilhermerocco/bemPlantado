-- MVP 2. Modelo: docs/modelo-banco-de-dados.jpg
--
-- Tabelas do modelo do projeto: registro, grupo_planta, usuario, favorito, insight.
-- Tabelas de apoio do sistema:  grupo_exemplo, planta, rega, configuracao.
--
-- Unidades (tabela registro):
--   temperature  graus Celsius (C)        pressure  hectopascal (hPa)
--   altitude     metros (m)               humidity  umidade RELATIVA DO AR (%)
--   "CO2"        ppm                      particula1 / particula2  microgramas por m3
--   registro_tempo  data e hora em UTC (o campo "timestamp" do MQTT, em segundos Unix)
-- Valores ausentes: a caixinha pode nao enviar todos os campos; o que faltar fica NULL
--   (por isso as colunas de medicao NAO sao NOT NULL).
-- Registros duplicados: registro_tempo e UNIQUE. Uma segunda mensagem com o mesmo instante
--   e IGNORADA (a ingestao confere antes de gravar; o banco garante mesmo em corrida).
-- "CO2" entre aspas para manter exatamente o nome pedido no projeto (sem aspas viraria co2).
-- =====================================================================

-- ------------------------------------------------------------ registro (leituras do sensor)
CREATE TABLE IF NOT EXISTS registro (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temperature     DOUBLE PRECISION,
    pressure        DOUBLE PRECISION,
    altitude        DOUBLE PRECISION,
    humidity        DOUBLE PRECISION,
    "CO2"           DOUBLE PRECISION,
    particula1      DOUBLE PRECISION,
    particula2      DOUBLE PRECISION,
    registro_tempo  TIMESTAMP NOT NULL
);
-- UNIQUE + indice: consulta por intervalo de tempo e ultima leitura ficam rapidas
CREATE UNIQUE INDEX IF NOT EXISTS ix_registro_registro_tempo ON registro (registro_tempo);

COMMENT ON TABLE  registro                IS 'Leituras da caixinha (uma linha por mensagem MQTT valida).';
COMMENT ON COLUMN registro.temperature    IS 'Temperatura em graus Celsius.';
COMMENT ON COLUMN registro.pressure       IS 'Pressao atmosferica em hPa.';
COMMENT ON COLUMN registro.altitude       IS 'Altitude em metros.';
COMMENT ON COLUMN registro.humidity       IS 'Umidade relativa do ar em %.';
COMMENT ON COLUMN registro."CO2"          IS 'Concentracao de CO2 em ppm.';
COMMENT ON COLUMN registro.particula1     IS 'Primeira medicao de particulas, em ug/m3.';
COMMENT ON COLUMN registro.particula2     IS 'Segunda medicao de particulas, em ug/m3.';
COMMENT ON COLUMN registro.registro_tempo IS 'Instante da medicao em UTC (vem do timestamp do MQTT). Unico.';

-- ------------------------------------------------------------ grupo_planta (base do sistema)
CREATE TABLE IF NOT EXISTS grupo_planta (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                 VARCHAR(80)  NOT NULL UNIQUE,
    exemplos             VARCHAR(255),           -- resumo; a lista completa fica em grupo_exemplo
    temp_min             DOUBLE PRECISION,       -- faixa de temperatura de referencia (C)
    temp_max             DOUBLE PRECISION,
    umid_min             DOUBLE PRECISION,       -- umidade do ar minima de referencia (%)
    umid_max             DOUBLE PRECISION,
    intervalo_rega_dias  INTEGER      NOT NULL DEFAULT 7 CHECK (intervalo_rega_dias > 0),
    dica_base            TEXT,                   -- cuidados gerais do grupo
    como_reconhecer      TEXT,
    onde_cultivadas      TEXT
);
COMMENT ON TABLE grupo_planta IS 'Os 15 grupos de plantas. Os numeros sao valores de referencia (aproximados) para cultivo domestico.';

CREATE TABLE IF NOT EXISTS grupo_exemplo (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id  INTEGER     NOT NULL REFERENCES grupo_planta (id) ON DELETE CASCADE,
    nome      VARCHAR(80) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_grupo_exemplo_grupo_id ON grupo_exemplo (grupo_id);

-- ------------------------------------------------------------ usuario e favorito (LGPD)
CREATE TABLE IF NOT EXISTS usuario (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    cpf         CHAR(11)     UNIQUE,            -- dado pessoal (LGPD)
    email       VARCHAR(255) NOT NULL UNIQUE,   -- dado pessoal (LGPD)
    telefone    VARCHAR(20),                    -- dado pessoal (LGPD)
    senha_hash  VARCHAR(255) NOT NULL,          -- nunca a senha: so o hash
    criado_em   TIMESTAMP    NOT NULL DEFAULT (NOW() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS favorito (
    usuario_id  INTEGER   NOT NULL REFERENCES usuario (id)      ON DELETE CASCADE,
    grupo_id    INTEGER   NOT NULL REFERENCES grupo_planta (id) ON DELETE CASCADE,
    criado_em   TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'utc'),
    PRIMARY KEY (usuario_id, grupo_id)           -- uma pessoa nao repete o mesmo grupo
);

-- ------------------------------------------------------------ insight (explica uma medicao para um grupo)
CREATE TABLE IF NOT EXISTS insight (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id     INTEGER   NOT NULL REFERENCES grupo_planta (id) ON DELETE CASCADE,
    registro_id  INTEGER   NOT NULL REFERENCES registro (id)     ON DELETE CASCADE,
    texto        TEXT      NOT NULL,
    modelo       VARCHAR(60),                    -- qual regra ou modelo gerou o texto
    criado_em    TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS ix_insight_grupo_id    ON insight (grupo_id);
CREATE INDEX IF NOT EXISTS ix_insight_registro_id ON insight (registro_id);

-- ------------------------------------------------------------ planta e rega (apoio ao aviso de rega)
CREATE TABLE IF NOT EXISTS planta (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id             INTEGER REFERENCES grupo_planta (id),
    apelido              VARCHAR(80)  NOT NULL,
    nome_popular         VARCHAR(120),
    nome_cientifico      VARCHAR(160),
    ambiente             VARCHAR(10)  NOT NULL DEFAULT 'interno' CHECK (ambiente IN ('interno', 'externo')),
    intervalo_rega_dias  INTEGER      NOT NULL DEFAULT 7 CHECK (intervalo_rega_dias > 0),
    temp_min             DOUBLE PRECISION,
    temp_max             DOUBLE PRECISION,
    umid_min             DOUBLE PRECISION,
    dica                 VARCHAR(300),
    fonte_dados          VARCHAR(160),
    ultima_rega          DATE,
    criada_em            TIMESTAMP DEFAULT (NOW() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS ix_planta_grupo_id ON planta (grupo_id);

CREATE TABLE IF NOT EXISTS rega (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planta_id  INTEGER NOT NULL REFERENCES planta (id) ON DELETE CASCADE,
    data       DATE    NOT NULL DEFAULT CURRENT_DATE
);
CREATE INDEX IF NOT EXISTS ix_rega_planta_data ON rega (planta_id, data);

-- ------------------------------------------------------------ configuracao (chave/valor do sistema)
CREATE TABLE IF NOT EXISTS configuracao (
    chave  VARCHAR(60) PRIMARY KEY,
    valor  VARCHAR(200)
);
